#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.txt: every Rust crate and npm package that ships inside LocalBooks,
// its license, the full text of every NOTICE file, and the license texts the packages carry.
//
//   node scripts/third-party-notices.mjs          regenerate the file
//   node scripts/third-party-notices.mjs --check  fail if the file is out of date (CI)
//
// Needs `npm ci` (for node_modules) and the crates of src-tauri/Cargo.lock (cargo fetches them).
// Shipped means: Rust crates reachable from localbooks through normal (not dev or build)
// dependencies on any target platform, and npm packages in package-lock.json not marked dev.

import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'THIRD-PARTY-NOTICES.txt');
const LEGAL_FILE = /^(licen[cs]e|copying|copyright|notice|unlicense)([-._].*)?$/i;
const NOTICE_FILE = /^notice([-._].*)?$/i;

const clean = (text) => text.replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trim();

const supplements = join(root, 'scripts', 'notices');

/**
 * License and NOTICE files at the top of a package directory, in name order, plus any file in
 * scripts/notices/extra/<name>/ that the published package leaves out (see the README there).
 */
function legalFiles(dir, name) {
  const read = (from, label) =>
    readdirSync(from)
      .filter((file) => LEGAL_FILE.test(file) && statSync(join(from, file)).isFile())
      .sort()
      .map((file) => ({ name: label(file), notice: NOTICE_FILE.test(file), text: clean(readFileSync(join(from, file), 'utf8')) }))
      .filter((f) => f.text);
  const files = read(dir, (file) => file);
  const extra = join(supplements, 'extra', name);
  if (existsSync(extra)) {
    for (const f of read(extra, (file) => `${file}, from the project's repository`)) {
      if (!files.some((own) => own.notice === f.notice)) files.push(f);
    }
  }
  return files;
}

function rustPackages() {
  const meta = JSON.parse(
    execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', join(root, 'src-tauri', 'Cargo.toml')], {
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
    }),
  );
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const queue = [meta.resolve.root];
  while (queue.length) {
    const node = nodes.get(queue.pop());
    for (const dep of node.deps) {
      if (seen.has(dep.pkg) || !dep.dep_kinds.some((k) => k.kind === null)) continue;
      seen.add(dep.pkg);
      queue.push(dep.pkg);
    }
  }
  return [...seen].map((id) => {
    const p = byId.get(id);
    return {
      ecosystem: 'Rust crate',
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? `see ${p.license_file}` : 'unspecified'),
      source: p.repository ?? `https://crates.io/crates/${p.name}`,
      files: legalFiles(dirname(p.manifest_path), p.name),
    };
  });
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  return Object.entries(lock.packages)
    .filter(([path, p]) => path.startsWith('node_modules/') && !p.dev && !p.devOptional)
    .map(([path, p]) => {
      const dir = join(root, path);
      if (!existsSync(dir)) throw new Error(`${path} is missing: run npm ci first`);
      const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      const repo = typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
      return {
        ecosystem: 'npm package',
        name: path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length),
        version: p.version,
        license: p.license ?? manifest.license ?? 'unspecified',
        source: repo ?? `https://www.npmjs.com/package/${manifest.name}`,
        files: legalFiles(dir, manifest.name),
      };
    });
}

function render(packages) {
  const id = (p) => `${p.name} ${p.version}`;
  const rule = (title) => `\n${'='.repeat(78)}\n${title}\n${'='.repeat(78)}\n`;
  const out = [
    'LocalBooks: third-party notices',
    '',
    'LocalBooks is released under the MIT License (see LICENSE). It includes the open-source',
    'components listed below, each under its own license. NOTICE files are reproduced in full,',
    'followed by the license texts the components carry.',
    '',
    'QuickBooks® is a registered trademark of Intuit Inc. LocalBooks is an independent project and',
    'is not affiliated with, endorsed by, or sponsored by Intuit Inc.',
    '',
    'Generated by scripts/third-party-notices.mjs; do not edit by hand.',
  ];

  for (const ecosystem of ['Rust crate', 'npm package']) {
    const list = packages.filter((p) => p.ecosystem === ecosystem);
    out.push(rule(`${ecosystem}s (${list.length})`));
    for (const p of list) out.push(`${id(p)}  [${p.license}]  ${p.source}`);
  }

  out.push(rule('NOTICE files'));
  const notices = packages.flatMap((p) => p.files.filter((f) => f.notice).map((f) => ({ p, f })));
  if (!notices.length) out.push('(none)');
  for (const { p, f } of notices) out.push(`----- ${p.ecosystem} ${id(p)}: ${f.name} -----\n\n${f.text}\n`);

  // Identical texts (most Apache-2.0 copies, for one) are printed once with everyone who uses them.
  out.push(rule('License texts'));
  const texts = new Map();
  for (const p of packages) {
    for (const f of p.files.filter((f) => !f.notice)) {
      if (!texts.has(f.text)) texts.set(f.text, []);
      texts.get(f.text).push(`${id(p)} (${f.name})`);
    }
  }
  for (const [text, users] of texts) out.push(`----- Used by: ${users.join(', ')} -----\n\n${text}\n`);

  const missing = packages.filter((p) => !p.files.some((f) => !f.notice));
  if (missing.length) {
    out.push(rule('Packages that ship no license file'));
    out.push('These are under the license named for them, whose standard text follows the list.\n');
    for (const p of missing) out.push(`${p.ecosystem} ${id(p)}  [${p.license}]`);
    const named = new Set(missing.flatMap((p) => p.license.split(/[\s()/]+|\bOR\b|\bAND\b/)).filter(Boolean));
    for (const spdx of [...named].sort()) {
      const file = join(supplements, 'licenses', `${spdx}.txt`);
      if (existsSync(file)) out.push(`\n----- Standard text: ${spdx} -----\n\n${clean(readFileSync(file, 'utf8'))}`);
    }
  }
  return `${out.join('\n')}\n`;
}

const byName = (a, b) => a.name.localeCompare(b.name, 'en') || a.version.localeCompare(b.version, 'en', { numeric: true });
const text = render([...rustPackages().sort(byName), ...npmPackages().sort(byName)]);

if (process.argv.includes('--check')) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
  if (current !== text) {
    const [had, want] = [current.split('\n'), text.split('\n')];
    const at = want.findIndex((line, i) => line !== had[i]);
    console.error(`First difference at line ${at + 1}:\n  file:     ${had[at] ?? '(end of file)'}\n  expected: ${want[at] ?? '(end of file)'}`);
    console.error('THIRD-PARTY-NOTICES.txt is out of date: run `node scripts/third-party-notices.mjs` and commit the result.');
    process.exit(1);
  }
  console.log('THIRD-PARTY-NOTICES.txt is up to date.');
} else {
  writeFileSync(output, text);
  console.log(`Wrote ${output} (${Math.round(text.length / 1024)} KB).`);
}
